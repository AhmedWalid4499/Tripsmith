/** Builds a 12-month climate table from parallel arrays (index 0 = January). */
function climate(highs: number[], lows: number[], rainyDays: number[]): MonthlyClimate {
  return highs.map((highC, i) => ({ highC, lowC: lows[i]!, rainyDays: rainyDays[i]! }));
}

